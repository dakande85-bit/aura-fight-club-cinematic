#!/usr/bin/env python3
"""End-to-end free synthetic-media smoke test for the cinematic trailer renderer."""
import json
import pathlib
import subprocess
import sys
import tempfile
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
RENDERER = ROOT / "scripts" / "render-cinematic-trailer.py"

with tempfile.TemporaryDirectory(prefix="aura-render-smoke-") as temp:
    directory = pathlib.Path(temp)
    photo = directory / "test.jpg"
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi",
                    "-i", "color=c=0x122030:s=180x320:r=24", "-frames:v", "1",
                    "-q:v", "4", "-threads", "1", str(photo)], check=True, timeout=30)
    shots = []
    for i, kind in enumerate(("real_photo", "reveal")):
        shots.append({
            "id": "test-" + str(i), "name": "test scene", "kind": kind, "duration": 1,
            "direction": "Smoke test only", "overlay_text": "TEST REVEAL" if i else "",
            "file": "media/test.jpg", "rights": "self_owned",
            "source_reference": "generated by AURA renderer CI smoke test",
            "rights_verified": True, "approved": True, "ai_illustration": False
        })
    manifest = {
        "schema": "aura-cinematic-trailer-v1", "version": 1,
        "title": "test", "fight_status": "hypothetical",
        "shots": shots, "narration_file": "", "music_file": "",
        "cover_file": "", "publication_status": "DRAFT_NOT_PUBLISHED"
    }
    pack = directory / "input.zip"
    with zipfile.ZipFile(pack, "w") as archive:
        archive.write(photo, arcname="media/test.jpg")
        archive.writestr("manifest.json", json.dumps(manifest))
    output = directory / "out.mp4"
    subprocess.run([sys.executable, str(RENDERER), str(pack), "--output", str(output)],
                   check=True, timeout=180)
    assert output.exists() and output.stat().st_size > 1000, "render did not produce a playable asset"
    probe = subprocess.check_output(["ffprobe", "-v", "error", "-show_entries",
                                     "stream=codec_name,width,height", "-of", "json", str(output)], text=True)
    streams = json.loads(probe)["streams"]
    assert any(x.get("codec_name") == "h264" and x.get("width") == 1080
               and x.get("height") == 1920 for x in streams), streams
    assert any(x.get("codec_name") == "aac" for x in streams), streams
    # A private rough cut must work without publication approval and stay watermarked.
    for shot in shots:
        shot["rights_verified"] = False
        shot["approved"] = False
    draftpack = directory / "rough-cut.zip"
    with zipfile.ZipFile(draftpack, "w") as archive:
        archive.write(photo, arcname="media/test.jpg")
        archive.writestr("manifest.json", json.dumps(manifest))
    draft_output = directory / "draft.mp4"
    subprocess.run([sys.executable, str(RENDERER), str(draftpack), "--output", str(draft_output), "--draft"],
                   check=True, timeout=180)
    assert draft_output.exists() and draft_output.stat().st_size > 1000
    print("AURA render smoke passed — reviewed + draft-labelled 2-second vertical trailers.")

