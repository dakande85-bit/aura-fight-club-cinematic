export function buildSupplierEmail(supplier, spec) {
  const subject = `${spec.product_name} - manufacturing sample request`;
  const body = [
    `Hi ${supplier.name} team,`,
    '',
    `I am preparing a premium AURA Fight Club product for production and would like to review your sampling options for ${spec.product_name}.`,
    '',
    'Product spec:',
    `- Category: ${spec.category}`,
    `- Supplier type needed: ${spec.supplier_type_needed}`,
    `- Material: ${spec.material}`,
    `- Fabric weight / GSM: ${spec.fabric_weight_gsm}`,
    `- Colourway: ${spec.colourway}`,
    `- Logo placement: ${spec.logo_placement}`,
    `- Typography notes: ${spec.typography_notes}`,
    `- Hardware: ${spec.hardware}`,
    `- Sole / padding / stitching: ${spec.sole_padding_stitching}`,
    `- Finish: ${spec.finish}`,
    `- Sizing: ${spec.sizing}`,
    `- Packaging: ${spec.packaging}`,
    `- Accuracy notes: ${spec.accuracy_notes}`,
    `- Manufacturing notes: ${spec.manufacturing_notes}`,
    `- Target price: ${spec.target_price}`,
    `- Target MOQ: ${spec.target_moq}`,
    '',
    'Reference image URLs:',
    ...spec.reference_image_urls.map((url) => `- ${url}`),
    '',
    'Please confirm sample cost, production MOQ, lead times, material options, logo methods, and any technical limitations.',
    '',
    'Best,',
    'AURA Fight Club',
  ].join('\n');

  return { subject, body };
}
